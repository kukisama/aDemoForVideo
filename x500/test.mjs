import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { mkdir, writeFile, readFile, stat } from 'node:fs/promises';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { resolve } from 'node:path';
import { createHash } from 'node:crypto';
import { DURATION, CHAPTERS, VOICE_CUES, FACTS } from './story.mjs';

const require = createRequire(new URL('../web/package.json', import.meta.url));
const { chromium } = require('playwright');
const root = fileURLToPath(new URL('../', import.meta.url));
const qa = resolve(root, 'x500/output/x500-qa');
const entry = resolve(root, 'export/X500/开始观看.html');
await mkdir(qa, { recursive: true });
const full = process.argv.includes('--full');
const channel = process.argv.includes('--edge') ? 'msedge' : 'chrome';
const browser = await chromium.launch({ channel, headless: !full });
const context = await browser.newContext({ viewport: { width: 1440, height: 900 }, reducedMotion: 'no-preference', offline: true });
const page = await context.newPage();
const errors = [], network = [], checks = [];
page.on('pageerror', error => errors.push(error.message));
page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
page.on('request', request => { if (/^https?:/.test(request.url())) network.push(request.url()); });
const url = pathToFileURL(entry).href;
const check = (condition, message) => { assert.ok(condition, message); checks.push(message); };
try {
  await page.goto(url, { waitUntil: 'load' });
  await page.waitForFunction(() => window.__X500__?.ready, null, { timeout: 30000 });
  const initial = await page.evaluate(() => window.__X500__.state);
  console.log('READY', JSON.stringify(initial));
  check(Math.abs(initial.audioDuration - DURATION) < .06, 'One-minute local audio ready');
  check(await page.locator('img,canvas,video').count() === 0, 'All visuals are HTML/CSS/SVG; no images, canvas or video');
  check(await page.locator('.phone').count() === 6, 'Six multi-plane HTML phone instances');
  check((await page.evaluate(() => window.__X500__.facts)).price === FACTS.price, 'Actual standard-edition official suggested price');
  const subtitles = await page.evaluate(() => window.__X500__.captions);
  check(subtitles.map(c => c.text).join('') === VOICE_CUES.map(c => c.text).join(''), 'All new narration covered by aligned subtitles');
  await page.screenshot({ path: resolve(qa, `${channel}-cover.png`) });
  const frames = [];
  for (const [time, name] of [[2.5, 'question'], [8.2, 'reveal'], [16.6, 'design'], [20.7, 'camera-main'], [26, 'camera-tele'], [32.5, 'motion'], [40, 'performance'], [48.7, 'battery'], [55.95, 'price'], [59, 'ending']]) {
    const state = await page.evaluate(t => window.__X500__.render(t), time);
    await page.screenshot({ path: resolve(qa, `${channel}-${name}.png`) });
    const active = CHAPTERS.find(c => time >= c.start && time < c.end);
    check(state.chapter === active.id, `Scene at ${time}s is ${active.id}`);
    check(Math.abs(state.time - time) < .03, `Audio and visuals seek together at ${time}s`);
    const count = await page.locator('.scene:not([hidden])').count();
    check(count === 1, `Exactly one scene displayed at ${time}s`);
    frames.push({ time, chapter: state.chapter, subtitle: state.subtitle });
  }
  await page.evaluate(() => window.__X500__.render(20.7));
  check(await page.locator('#camera-number').textContent() === '50', 'Main-camera number accompanies main-camera narration');
  await page.evaluate(() => window.__X500__.render(21.5));
  check(await page.locator('#camera-number').textContent() === '64', 'Telephoto number accompanies telephoto narration');
  await page.evaluate(() => window.__X500__.render(55.2));
  check(await page.locator('#price-reveal').evaluate(e => Number(getComputedStyle(e).opacity)) === 0, 'Price remains hidden before reveal');
  await page.evaluate(() => window.__X500__.render(55.95));
  check(await page.locator('#price-reveal').evaluate(e => Number(getComputedStyle(e).opacity)) > .99, 'Price revealed with actual spoken price timing');
  await page.evaluate(() => window.__X500__.seek(0));
  await page.locator('#toggle').click();
  await page.waitForFunction(() => window.__X500__.state.time > .7);
  await page.keyboard.press('Space');
  const paused = await page.evaluate(() => window.__X500__.state);
  await page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))));
  check(!(await page.evaluate(() => window.__X500__.state.playing)), 'Keyboard pause stops playback');
  check(await page.evaluate(() => window.__X500__.state.time) === paused.time, 'Paused audio clock does not advance');
  await page.keyboard.press('ArrowRight');
  check(Math.abs((await page.evaluate(() => window.__X500__.state.time)) - paused.time - 2) < .03, 'Keyboard seek follows audio time');
  await page.locator('#mute').click();
  check(await page.locator('#mute').getAttribute('aria-pressed') === 'true', 'Mute works');
  await page.locator('#mute').click();
  await page.locator('#sources-button').click();
  check(await page.locator('#sources').isVisible(), 'Official sources and qualifiers accessible');
  check(await page.locator('#sources a[href^="https://www.vivo.com.cn/"]').count() >= 6, 'Specific official citations supplied');
  await page.locator('#close-sources').click();
  let fullPlayback = null;
  if (full) {
    await page.evaluate(() => window.__X500__.seek(0));
    await page.locator('#fullscreen').click();
    await page.waitForFunction(() => document.fullscreenElement?.id === 'cinema');
    await page.locator('#toggle').click();
    await page.waitForFunction(() => window.__X500__.state.time >= 2 && document.querySelector('#cinema').classList.contains('controls-hidden'));
    const dimensions = await page.evaluate(() => window.__X500__.state.dimensions);
    check(Math.abs(dimensions.width / dimensions.height - 16 / 9) < .002, 'Native fullscreen preserves 16:9 geometry');
    check(await page.locator('#controls').evaluate(e => getComputedStyle(e).visibility) === 'hidden', 'Fullscreen control bar hides for recording');
    for (const chapter of CHAPTERS.slice(1)) {
      await page.waitForFunction(target => window.__X500__.state.time >= target, chapter.start + .5, { timeout: 20000 });
      check((await page.evaluate(() => window.__X500__.state)).chapter === chapter.id, `Real-time chronological playback reached ${chapter.id}`);
    }
    await page.waitForFunction(() => window.__X500__.state.ended, null, { timeout: 15000 });
    fullPlayback = await page.evaluate(() => window.__X500__.state);
    check(fullPlayback.time >= 59.99 && fullPlayback.time <= 60, 'End state is exactly one minute');
    check(fullPlayback.elapsedMs >= 59000 && fullPlayback.elapsedMs <= 62500, 'No accumulated drift from actual audio clock');
    await page.locator('#replay-overlay').click();
    await page.waitForFunction(() => window.__X500__.state.playing && window.__X500__.state.time > .3 && window.__X500__.state.time < 3);
    check(true, 'Replay after complete film works');
    await page.keyboard.press('Space');
    await page.evaluate(() => document.exitFullscreen());
  }
  await page.setViewportSize({ width: 390, height: 844 });
  await page.evaluate(() => window.__X500__.render(8.2));
  await page.screenshot({ path: resolve(qa, `${channel}-mobile.png`) });
  check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Mobile layout has no horizontal overflow');
  const collectionPath = entry;
  await page.goto(pathToFileURL(collectionPath).href, { waitUntil: 'load' });
  await page.waitForFunction(() => window.__X500__?.ready, null, { timeout: 30000 });
  check((await page.evaluate(() => window.__X500__.state.currentSource)).endsWith('/audio/master.mp3'), 'Portable collection resolves its own relative audio');
  check(network.length === 0, 'Offline file playback makes zero network requests');
  check(errors.length === 0, 'No browser script/resource errors');
  const report = { result: 'PASS', entry, browser: await browser.version(), channel, full, checks, frames, fullPlayback, errors, network, htmlBytes: (await stat(entry)).size, masterSha256: createHash('sha256').update(await readFile(resolve(root, 'x500/audio/master.mp3'))).digest('hex') };
  await writeFile(resolve(qa, `${channel}-${full ? 'full-' : ''}report.json`), JSON.stringify(report, null, 2));
  console.log('PASS', JSON.stringify({ checks: checks.length, browser: report.browser, channel, full, fullPlayback }));
} finally { await browser.close(); }